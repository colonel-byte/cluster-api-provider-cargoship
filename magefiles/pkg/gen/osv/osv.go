// Package osv writes the osv-scanner.toml overrides that sit beside the non-Go dependency
// manifests `go mod vendor` copies into vendor/, and verifies that every one of them is present
// and that no manifest has appeared without one. See docs/agent/choice-osv-vendor-overrides.md.
package osv

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// Override is one generated osv-scanner.toml: the directory it is written to, the manifest it
// covers, that manifest's ecosystem, and what the manifest actually pins.
type Override struct {
	Dir       string
	Manifest  string
	Ecosystem string
	What      string
}

// Overrides is every non-Go dependency manifest in vendor/. An entry whose manifest has gone
// away is an error rather than a no-op, and a manifest with no entry is an error too, so this
// list is the whole truth about the tree and VerifyVendor holds it to that.
var Overrides = []Override{
	{
		Dir:       "vendor/github.com/theupdateframework/go-tuf",
		Manifest:  "requirements-test.txt",
		Ecosystem: "PyPI",
		What:      "the Python harness go-tuf runs its own conformance tests under",
	},
	{
		Dir:       "vendor/github.com/txn2/txeh",
		Manifest:  "requirements-docs.txt",
		Ecosystem: "PyPI",
		What:      "the MkDocs toolchain that builds txeh's documentation site",
	},
	{
		Dir:       "vendor/go.opentelemetry.io/otel",
		Manifest:  "requirements.txt",
		Ecosystem: "PyPI",
		What:      "the codespell pin otel's own spelling check installs",
	},
}

// OverrideName is the filename osv-scanner looks for beside a manifest. It reads configuration
// relative to the manifest it is scanning rather than from the root of the scan, which is the
// only reason these files are scattered through vendor/ instead of sitting in one place.
const OverrideName = "osv-scanner.toml"

func ecosystemLanguage(ecosystem string) string {
	switch ecosystem {
	case "npm":
		return "JavaScript"
	case "PyPI":
		return "Python"
	default:
		return ecosystem
	}
}

const commentWidth = 96

func comment(paragraphs ...string) string {
	var b strings.Builder
	for i, p := range paragraphs {
		if i > 0 {
			b.WriteString("#\n")
		}
		line := "#"
		for _, word := range strings.Fields(p) {
			if len(line)+1+len(word) > commentWidth {
				b.WriteString(line + "\n")
				line = "#"
			}
			line += " " + word
		}
		b.WriteString(line + "\n")
	}
	return b.String()
}

// OverrideContent renders the osv-scanner.toml for one override. The comment is addressed to
// whoever finds the file while reading vendored third-party source, which is the only way anyone
// comes across it.
func OverrideContent(o Override) string {
	return comment(
		`Generated by "make vendor". Do not edit, and do not delete.`,
		fmt.Sprintf(`%s here is %s. It is not a dependency of this module -- go mod vendor copies it in `+
			`because it sits in the directory of a module this provider imports Go packages from, and `+
			`nothing it names is compiled, executed or shipped.`, o.Manifest, o.What),
		`OpenSSF Scorecard runs osv-scanner over the whole checkout and scores Vulnerabilities as `+
			`ten minus the number of findings, so without this file every advisory ever filed `+
			`against those packages costs the repository a point. See `+
			`docs/agent/choice-osv-vendor-overrides.md.`,
	) + fmt.Sprintf(`
[[PackageOverrides]]
ecosystem = %q
ignore = true
reason = %q
`,
		o.Ecosystem,
		ecosystemLanguage(o.Ecosystem)+" tooling vendored alongside a Go module; not built, run or shipped by this provider",
	)
}

// WriteOverrides writes every override into vendor/, and fails if the manifest an entry names is
// not there -- which turns a dependency bump that dropped the module into an error on the commit
// that caused it, rather than a file quietly covering nothing.
func WriteOverrides() error {
	for _, o := range Overrides {
		if _, err := os.Stat(filepath.Join(o.Dir, o.Manifest)); err != nil {
			return fmt.Errorf("osv override for %s: %w -- the manifest is gone, so drop the entry from Overrides", o.Dir, err)
		}
		path := filepath.Join(o.Dir, OverrideName)
		if err := os.WriteFile(path, []byte(OverrideContent(o)), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
		fmt.Println("wrote", path)
	}
	return nil
}

// ForeignManifest reports whether name is a dependency manifest for an ecosystem other than Go.
// The list is what osv-scanner itself extracts, because a manifest it does not read costs
// nothing and one it does read costs a point.
func ForeignManifest(name string) bool {
	switch name {
	case "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock",
		"Pipfile.lock", "poetry.lock", "pdm.lock", "uv.lock",
		"Gemfile.lock", "Cargo.lock", "composer.lock", "mix.lock",
		"pubspec.lock", "conan.lock", "gradle.lockfile", "packages.lock.json",
		"pom.xml":
		return true
	}
	return strings.Contains(name, "requirements") && strings.HasSuffix(name, ".txt")
}

// VerifyVendor checks that vendor/ holds every declared override with the bytes WriteOverrides
// would write, and -- the half that matters more -- that no manifest in the tree is uncovered.
// Without the second check, a dependency bump that pulled in a module carrying a Gemfile.lock
// would drop the score on some later Scorecard run with nothing in the diff to point at.
func VerifyVendor() error {
	var problems []string

	covered := make(map[string]string, len(Overrides))
	for _, o := range Overrides {
		covered[filepath.Clean(o.Dir)] = o.Ecosystem

		path := filepath.Join(o.Dir, OverrideName)
		got, err := os.ReadFile(path)
		if err != nil {
			problems = append(problems, fmt.Sprintf("%s is missing (%v)", path, err))
			continue
		}
		if string(got) != OverrideContent(o) {
			problems = append(problems, fmt.Sprintf("%s does not match the generated override content", path))
		}
	}

	err := filepath.WalkDir("vendor", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !ForeignManifest(d.Name()) {
			return nil
		}
		if _, ok := covered[filepath.Dir(path)]; !ok {
			problems = append(problems, fmt.Sprintf("%s is a non-Go dependency manifest with no entry in Overrides", path))
		}
		return nil
	})
	if err != nil {
		return fmt.Errorf("walking vendor: %w", err)
	}

	if len(problems) > 0 {
		return fmt.Errorf("vendored osv-scanner overrides are out of date:\n  %s\n"+
			"a missing or mismatched override is rewritten by `make vendor-osv`; "+
			"an uncovered manifest needs an entry in Overrides first",
			strings.Join(problems, "\n  "))
	}
	fmt.Printf("%d osv-scanner overrides present and current\n", len(Overrides))
	return nil
}
