// Package docs writes the two pages of the book that are generated rather than written: the
// landing page, which is a copy of README.md, and SUMMARY.md, which is its table of contents.
//
// It is a package rather than a function in the magefile so that the part worth testing -- which
// label each chapter entry gets, and in what order -- can be tested without mage. The magefile is
// the entry point and holds no logic; see magefiles/generate.go.
package docs

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// generatedBanner marks a page as generator output, so an editor who opens one is told before they
// change it that their change will not survive the next `make generate`. The same note cargoship's
// own generated pages carry, in the same place.
const generatedBanner = "<!-- Page generated by `make docs`; DO NOT EDIT -->"

// chapter is one part of the book: a heading in SUMMARY.md and the directory under docs/ whose
// pages are listed beneath it.
type chapter struct {
	// title is the part heading, which mdBook renders as a sidebar section.
	title string
	// dir is the directory under docs/ holding the chapter's pages.
	dir string
}

// chapters is the book's structure, and the order is load-bearing twice over.
//
// docs/css/print.css drops everything from the first Development heading to the end of the
// document out of the print page, which is why Development and the decision records come last and
// in that order -- a chapter added after them is excluded from print too, and a chapter added
// before Development is not. The sidebar order is the other reason, and the less important one.
var chapters = []chapter{
	{title: "Guides", dir: "guides"},
	{title: "Development", dir: "dev"},
	{title: "Decision records", dir: "agent"},
}

// rootLinkPrefix is the `](docs/` that README.md's links carry and the landing page must not.
var rootLinkPrefix = regexp.MustCompile(`\]\(docs/`)

// licenseLink is README.md's link to the license, which is outside the book entirely.
const (
	licenseLink     = "](LICENSE)"
	licenseAbsolute = "](https://github.com/colonel-byte/cluster-api-provider-cargoship/blob/main/LICENSE)"
)

// Generate writes both generated pages, relative to the repository root.
func Generate(root string) error {
	if err := landingPage(root); err != nil {
		return err
	}
	return summary(root)
}

// landingPage copies README.md to docs/index.md, rewriting its links.
//
// A copy rather than a symlink: mdBook's behaviour on a symlinked chapter is not something to
// depend on, and a broken landing page is silent -- `mdbook build` does not fail on it.
//
// The rewrite is the part that is easy to miss. README.md's links are relative to the repository
// root and the copy is read from docs/, so every `docs/...` link in it would resolve one level too
// deep and every one of them would be dead in the published book -- silently, because nothing in
// the build checks a relative link. Stripping the prefix makes them relative to docs/ instead, and
// the license becomes absolute because it is not in the book at all.
func landingPage(root string) error {
	readme, err := os.ReadFile(filepath.Join(root, "README.md"))
	if err != nil {
		return fmt.Errorf("unable to read README.md: %w", err)
	}

	page := rootLinkPrefix.ReplaceAllString(string(readme), "](")
	page = strings.ReplaceAll(page, licenseLink, licenseAbsolute)

	out := filepath.Join(root, "docs", "index.md")
	fmt.Println(filepath.ToSlash(filepath.Join("docs", "index.md")))
	// No banner on this one: it is the book's front page, and an HTML comment would be the first
	// thing a reader sees. README.md itself is where an editor would go, and the copy is in
	// GENERATED_PATHS so `make verify` catches an edit to the wrong one.
	return os.WriteFile(out, []byte(page), 0o644)
}

// summary writes docs/SUMMARY.md from whatever pages are on disk.
//
// Generated rather than hand-maintained for one reason: a page that is added and not listed here
// is not in the book, and mdBook does not say so -- it builds a book the page is simply missing
// from. The same is true of a page that is deleted and still listed, except that one is a dead
// link in the sidebar.
func summary(root string) error {
	var b strings.Builder

	b.WriteString(generatedBanner + "\n\n")
	b.WriteString("# Summary\n\n")
	// A line before the first list item is a prefix chapter: mdBook gives it no number and places
	// it ahead of every chapter, which is where the front page belongs.
	b.WriteString("[Introduction](index.md)\n")

	for _, c := range chapters {
		entries, err := chapterEntries(root, c.dir)
		if err != nil {
			return err
		}
		if len(entries) == 0 {
			// A chapter with no pages is left out rather than written empty: mdBook renders an
			// empty part heading as a sidebar section with nothing under it.
			continue
		}

		b.WriteString("\n# " + c.title + "\n\n")
		for _, e := range entries {
			b.WriteString(e + "\n")
		}
	}

	out := filepath.Join(root, "docs", "SUMMARY.md")
	fmt.Println(filepath.ToSlash(filepath.Join("docs", "SUMMARY.md")))
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// chapterEntries is one chapter's list items, sorted by file name.
//
// The label is the file name without its extension, which is how cargoship labels the entries of
// its own generated chapters. It makes the sidebar a list of slugs rather than of titles, and buys
// the thing that matters more here: the entry for a page is derived from nothing but the page's
// path, so no part of a page's content can change what the table of contents says, and a page
// renamed is an entry renamed.
//
// Sorted by name, and not left in the order the filesystem hands them over: the output has to be
// byte-identical from one run to the next or `make verify` fails on a repository nobody changed.
// Name order also groups the `choice-` and `todo-` records together.
func chapterEntries(root, dir string) ([]string, error) {
	pattern := filepath.Join(root, "docs", dir, "*.md")
	paths, err := filepath.Glob(pattern)
	if err != nil {
		return nil, fmt.Errorf("unable to list %s: %w", pattern, err)
	}
	sort.Strings(paths)

	entries := make([]string, 0, len(paths))
	for _, path := range paths {
		name := filepath.Base(path)
		entries = append(entries, fmt.Sprintf("- [%s](%s/%s)", strings.TrimSuffix(name, ".md"), dir, name))
	}
	return entries, nil
}
